#!/usr/bin/env python3
"""Positive controls for apps/web/src/typeScaleUnits.test.ts.

Every control is a ONE-EDIT mutation of the PRODUCT (preset.ts or theme.css) plus a NAMED
PREDICTION of which test case must red and which must stay green. The verdict is read from the
set of failing test NAMES, never from an exit code:

  · an exit code cannot tell a caught mutation from a file that no longer parses;
  · a control that reds three cases when it was predicted to red one has not been understood,
    even though "CAUGHT" would print either way.

So each row carries BOTH halves — `reds` (must fail) and everything else (must stay green) — and
a control scores CAUGHT only when the failing set is EXACTLY the predicted set. Two rows are
predicted NOT CAUGHT on purpose: a guard that reds on every edit to preset.ts is a guard that
gets deleted at the next merge, so proving it distinguishes a unit change from a leading change
is part of the campaign, not politeness.

Anchors are asserted to appear EXACTLY ONCE before any write, and the tree is restored in a
`finally` with a closing sha256 check — a crash between mutate and restore must not leave a
mutated scale on disk.

Usage:  python3 scripts/w11-type-scale-controls.py
"""
