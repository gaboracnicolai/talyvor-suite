def run_guard() -> dict:
    """Run ONLY the guard file and return {test name: [messages]} for the failures."""
    with tempfile.NamedTemporaryFile(suffix=".json", delete=False) as fh:
        report = Path(fh.name)
    try:
        subprocess.run(
            ["npx", "vitest", "run", TEST, "--reporter=json", f"--outputFile={report}"],
            cwd=WEB, capture_output=True, text=True, timeout=600,
        )
        try:
            data = json.loads(report.read_text())
        except Exception:
            return {"__COLLECTION_ERROR__": ["the guard file did not run at all"]}
        failed, total = {}, 0
        for tr in data.get("testResults", []):
            for ar in tr.get("assertionResults", []):
                total += 1
                if ar.get("status") == "failed":
                    failed[ar.get("title", "")] = ar.get("failureMessages", [])
        if total == 0:
            return {"__NO_TESTS_RAN__": ["the guard file produced no assertions"]}
        return failed
    finally:
        report.unlink(missing_ok=True)


def main() -> int:
    sha_before = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in (PRESET, THEME)}
    backups = {p: p.read_text() for p in (PRESET, THEME)}

    print("BASELINE (no mutation) — every case must be green, or every verdict below is noise")
    base_failures = run_guard()
    if base_failures:
        print(f"  FAIL: the guard is not green before the campaign: {list(base_failures)}")
        return 2
    print("  ok\n")

    results = []
    try:
        for c in CONTROLS:
            path, find = c["file"], c["find"]
            text = backups[path]
            # A control must prove its own premise before it writes anything.
            n = text.count(find)
            if n != 1:
                print(f"{c['id']}  ANCHOR NOT UNIQUE ({n} matches) — control not run: {find[:60]!r}")
                results.append((c, "ANCHOR", set(), set()))
                continue
            mutated = text.replace(find, c["repl"])
            assert mutated != text, f"{c['id']} rewrote nothing"
            path.write_text(mutated)
            got = run_guard()
            path.write_text(text)

            predicted = set(c["reds"])
            actual = set(got)
            if predicted == actual:
                verdict = "CAUGHT" if predicted else "NOT CAUGHT (as predicted)"
            else:
                verdict = "MISPREDICTED"
            results.append((c, verdict, predicted, actual))
            print(f"{c['id']}  {verdict}")
            print(f"    mutation : {c['what']}")
            print(f"    predicted: {c['expect']}")
            for name in sorted(actual):
                msg = (got[name][0] if got[name] else "").strip().splitlines()
                first = next((ln for ln in msg if ln.strip()), "")
                print(f"    reddened : {name}")
                print(f"               {first[:150]}")
            if verdict == "MISPREDICTED":
                print(f"    expected reds: {sorted(predicted)}")
            print()
    finally:
        for p, t in backups.items():
            p.write_text(t)
        sha_after = {p: hashlib.sha256(p.read_bytes()).hexdigest() for p in (PRESET, THEME)}
        assert sha_after == sha_before, f"RESTORE FAILED: {sha_after} != {sha_before}"
        print("restored: sha256 of preset.ts and theme.css match the pre-campaign bytes")

    caught = sum(1 for _, v, _, _ in results if v.startswith("CAUGHT"))
    inert = sum(1 for _, v, _, _ in results if v.startswith("NOT CAUGHT"))
    bad = [c["id"] for c, v, _, _ in results if v in ("MISPREDICTED", "ANCHOR")]
    print(f"\n{caught} caught by the predicted case, {inert} inert as predicted, "
          f"{len(bad)} mispredicted{': ' + ', '.join(bad) if bad else ''}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
